package top.xiaojiang233.wetypemulti.common.dict

import top.xiaojiang233.wetypemulti.common.romaji.Romaji
import java.io.Reader

enum class DictFormat {
    /** `reading<TAB>word[<TAB>weight]`, `#` comments. */
    TSV,
    /** Mozc/Google Japanese Input: `reading<TAB>lid<TAB>rid<TAB>cost<TAB>word`. */
    MOZC,
    /** Rime `*.dict.yaml`: YAML header, `...`, then `word<TAB>code[<TAB>weight]`; code is romaji. */
    RIME,
}

/** Imports user dictionaries into [Entry] lists and exports them as Rime dictionaries. */
object DictImporter {
    fun detect(firstLines: List<String>): DictFormat {
        if (firstLines.any { it.trim() == "---" } ) return DictFormat.RIME
        val data = firstLines.firstOrNull { it.isNotBlank() && !it.startsWith("#") } ?: return DictFormat.TSV
        val cols = data.split('\t')
        return if (cols.size >= 5 && cols[1].toIntOrNull() != null && cols[2].toIntOrNull() != null) DictFormat.MOZC else DictFormat.TSV
    }

    fun import(reader: Reader, format: DictFormat? = null): List<Entry> {
        val lines = reader.readLines().map { it.removePrefix("﻿") }
        val fmt = format ?: detect(lines.take(50))
        return when (fmt) {
            DictFormat.TSV -> lines.mapNotNull(::parseTsv)
            DictFormat.MOZC -> lines.mapNotNull(::parseMozc)
            DictFormat.RIME -> parseRime(lines)
        }
    }

    private fun parseTsv(line: String): Entry? {
        if (line.isBlank() || line.startsWith("#")) return null
        val c = line.split('\t')
        if (c.size < 2) return null
        return Entry(Romaji.toHiragana(c[0].trim()), c[1].trim(), c.getOrNull(2)?.trim()?.toIntOrNull() ?: 0)
    }

    private fun parseMozc(line: String): Entry? {
        if (line.isBlank() || line.startsWith("#")) return null
        val c = line.split('\t')
        if (c.size < 5) return null
        // Mozc cost: lower is better; map to a weight where higher is better.
        val cost = c[3].toIntOrNull() ?: 8000
        return Entry(Romaji.toHiragana(c[0].trim()), c[4].trim(), (10000 - cost).coerceAtLeast(0))
    }

    private fun parseRime(lines: List<String>): List<Entry> {
        val start = lines.indexOfFirst { it.trim() == "..." }.let { if (it < 0) 0 else it + 1 }
        return lines.drop(start).mapNotNull { line ->
            if (line.isBlank() || line.startsWith("#")) return@mapNotNull null
            val c = line.split('\t')
            if (c.size < 2) return@mapNotNull null
            val code = c[1].trim()
            // The code may be romaji (with spaces between syllables) or already kana.
            val reading = if (code.any { it in 'a'..'z' || it in 'A'..'Z' })
                Romaji.toKana(code.replace(" ", "")) else Romaji.toHiragana(code)
            Entry(reading, c[0].trim(), c.getOrNull(2)?.trim()?.toIntOrNull() ?: 0)
        }
    }

    /** Render entries as a Rime dictionary (`code` column is Hepburn romaji). */
    fun toRimeDict(name: String, entries: Iterable<Entry>, version: String = "1.0"): String = buildString {
        append("# Generated by wetype-multilanguage\n---\nname: $name\nversion: \"$version\"\nsort: by_weight\n...\n")
        for (e in entries) append("${e.word}\t${Romaji.toRomaji(e.reading)}\t${e.weight}\n")
    }
}
